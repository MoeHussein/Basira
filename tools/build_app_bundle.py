"""Bundle the app into one self-contained HTML file and a gzipped C header for the firmware.
    python3 tools/build_app_bundle.py
writes  dist/BASIRA_app.html                  (open in a browser: simulator mode works offline)
        firmware/basira_fw/app_bundle.h       (served by the device at http://192.168.4.1)
Scripts referenced as <script src="js/NAME.js"></script> in app/index.html are inlined in order."""
import gzip, os, re, sys
ROOT = os.path.normpath(os.path.join(os.path.dirname(__file__), ".."))
src = os.path.join(ROOT, "app", "index.html")
html = open(src, encoding="utf-8").read()
def inline(m):
    path = os.path.join(ROOT, "app", m.group(1))
    return "<script>\n" + open(path, encoding="utf-8").read() + "\n</script>"
out = re.sub(r'<script src="(js/[\w.-]+\.js)"></script>', inline, html)
assert 'src="js/' not in out, "un-inlined script left"
os.makedirs(os.path.join(ROOT, "dist"), exist_ok=True)
open(os.path.join(ROOT, "dist", "BASIRA_app.html"), "w", encoding="utf-8").write(out)
gz = gzip.compress(out.encode("utf-8"), compresslevel=9, mtime=0)
lines = [", ".join(f"0x{b:02x}" for b in gz[i:i + 20]) for i in range(0, len(gz), 20)]
hdr = ("// GENERATED by tools/build_app_bundle.py from app/ - do not edit.\n#pragma once\n#include <stdint.h>\n#include <stddef.h>\n"
       f"static const size_t APP_HTML_GZ_LEN = {len(gz)};\nstatic const uint8_t APP_HTML_GZ[] = {{\n" + ",\n".join(lines) + "\n};\n")
open(os.path.join(ROOT, "firmware", "basira_fw", "app_bundle.h"), "w").write(hdr)
print(f"app: {len(out)} bytes -> gzip {len(gz)} bytes; wrote dist/BASIRA_app.html and firmware/basira_fw/app_bundle.h")
