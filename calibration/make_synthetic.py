"""Make a SYNTHETIC calibration dataset from known 'true' parameters (for testing the fit; not device data).
    python3 make_synthetic.py [out.csv]"""
import csv, math, os, random, sys
from calib_model import FIELDS, positions, predict, pv_to_rx

TRUTH = {"R": {"P0": 0.14, "k": 1.94, "Pp": 3.06, "Pm": -2.96, "zero_a": 4.3, "zero_b": -2.7, "J0off": 0.035, "J45off": -0.02},
         "L": {"P0": -0.09, "k": 2.05, "Pp": 2.97, "Pm": -3.04, "zero_a": -3.1, "zero_b": 1.8, "J0off": -0.025, "J45off": 0.03}}
MECH = {"r": 5.0, "zero_plate": 120.0, "sign_p": 1, "sign_a": 1, "sign_b": -1}
NOISE_D, NOISE_AX = 0.02, 0.5     # digital lensmeter: power noise (D, 1 sd), axis noise (deg, 1 sd); readings rounded to 0.01 D and 1 deg

def main(out):
    random.seed(11)
    rows = []
    for eye in ("R", "L"):
        for i in range(60):
            row = {"point": f"{eye}{i:02d}", "set": "fit" if i < 40 else "holdout", "eye": eye,
                   "raw_plate": MECH["zero_plate"] + math.degrees(random.uniform(-4.5, 4.5) / MECH["r"]),
                   "raw_ringP": random.uniform(0, 360), "raw_ringM": random.uniform(0, 360)}
            pv = predict(row, MECH, TRUTH[eye])
            S, C, ax = pv_to_rx(*pv)
            row["lens_S"] = round(S + random.gauss(0, NOISE_D), 2)
            row["lens_C"] = round(min(0.0, C + random.gauss(0, NOISE_D)), 2)
            row["lens_ax"] = round((ax + random.gauss(0, NOISE_AX if abs(C) > 0.25 else 3)) % 180, 0) or 180.0
            rows.append(row)
    with open(out, "w", newline="") as f:
        f.write("# SYNTHETIC calibration data generated by calibration/make_synthetic.py - NOT measured on a device\n")
        for eye in ("R", "L"):
            f.write(f"# {eye}.pinion_r_mm={MECH['r']}\n# {eye}.zero_plate={MECH['zero_plate']}\n# {eye}.sign_plate={MECH['sign_p']}\n# {eye}.sign_ringP={MECH['sign_a']}\n# {eye}.sign_ringM={MECH['sign_b']}\n")
        w = csv.DictWriter(f, FIELDS); w.writeheader()
        for r in rows: w.writerow({k: (round(v, 3) if isinstance(v, float) else v) for k, v in r.items()})
    print(f"wrote {out}: {len(rows)} readings (40 fit + 20 held-out per eye)")

if __name__ == "__main__":
    main(sys.argv[1] if len(sys.argv) > 1 else os.path.join(os.path.dirname(__file__), "examples", "SYNTHETIC_calibration_readings.csv"))
